local T = T

T.it("a fresh TuttiDB gets the defaults", function()
    local G, W, ns = T.load()
    local s = G.TuttiDB.settings
    T.eq(s.rollInTutti, true)
    T.eq(s.closeAfter, 10)
    T.eq(s.sound, "chime")
    T.eq(s.accent, "class")
    T.eq(s.scale, 1)
    local w = G.TuttiDB.window
    T.eq(w.point, "TOPLEFT")
    T.eq(w.x, 372)
    T.eq(w.y, -226)
    T.eq(type(G.TuttiDB.recent), "table")
    T.eq(#G.TuttiDB.recent, 0)
    T.eq(G.TuttiDB.schema, 1)
    T.eq(ns.DB, G.TuttiDB)
    T.eq(ns.Get("closeAfter"), 10)
    T.eq(ns.DB.window.x, 372)
end)

T.it("Set fires SETTING_CHANGED once and skips equal values", function()
    local G, W, ns = T.load()
    local seen = {}
    ns.Listen("SETTING_CHANGED", function(k, v) seen[#seen + 1] = k .. "=" .. tostring(v) end)
    ns.Set("sound", "none")
    T.eq(G.TuttiDB.settings.sound, "none")
    T.eq(#seen, 1, "one message")
    T.eq(seen[1], "sound=none")
    ns.Set("sound", "none")
    T.eq(#seen, 1, "the same value again says nothing")
    ns.Set("scale", 1)
    T.eq(#seen, 1, "a value equal to the default says nothing")
    ns.Set("scale", 1.2)
    T.eq(seen[2], "scale=1.2")
    T.eq(ns.Get("scale"), 1.2)
end)

T.it("Get falls back to the default for a setting that was never stored", function()
    local G, W, ns = T.load()
    G.TuttiDB.settings.sound = nil
    T.eq(ns.Get("sound"), "chime")
    T.eq(ns.Get("nothingLikeThis"), nil)
end)

T.it("an existing TuttiDB keeps its values and unknown keys", function()
    local G, W, ns = T.load({ db = { settings = { sound = "none", future = 1 }, extra = true,
        window = { point = "CENTER", x = 5, y = 6 } } })
    T.eq(ns.Get("sound"), "none")
    T.eq(G.TuttiDB.settings.future, 1)
    T.eq(G.TuttiDB.extra, true)
    T.eq(ns.Get("closeAfter"), 10, "missing keys get defaults")
    T.eq(G.TuttiDB.window.point, "CENTER", "a saved position stays")
    T.eq(G.TuttiDB.window.x, 5)
    T.eq(G.TuttiDB.window.y, 6)
end)

T.it("a damaged TuttiDB is repaired", function()
    local G, W, ns = T.load({ db = "garbage" })
    T.eq(type(G.TuttiDB), "table")
    T.eq(ns.Get("closeAfter"), 10)
    G, W, ns = T.load({ db = { settings = "oops", window = 5, recent = false } })
    T.eq(type(G.TuttiDB.settings), "table")
    T.eq(ns.Get("sound"), "chime")
    T.eq(G.TuttiDB.window.x, 372)
    T.eq(type(G.TuttiDB.recent), "table")
end)

T.it("DB_READY fires when the database is in place, and only for Tutti", function()
    -- T.load fires ADDON_LOADED itself, so load Init alone, listen, then bring the DB file in.
    local G, W, ns = T.load({ only = { "Core/Init.lua" }, login = false })
    local ready
    ns.Listen("DB_READY", function() ready = ns.DB end)
    local chunk = assert(loadfile("Core/DB.lua"))
    setfenv(chunk, G)
    chunk("Tutti", ns)
    T.no(ready, "nothing before ADDON_LOADED")
    W.fire("ADDON_LOADED", "SomeOtherAddon")
    T.no(ready, "nothing for another addon")
    W.fire("ADDON_LOADED", "Tutti")
    T.ok(ready, "DB_READY fired")
    T.eq(ready, G.TuttiDB, "with the database set")
end)
